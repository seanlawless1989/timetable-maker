"""Packs the logo and brand pictures into assets-data.js.

Run this after adding or changing files in assets/ (python3 tools/build_assets.py).
Embedding the images lets the page draw and download timetables even when
index.html is opened straight from a folder."""
import base64, json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = {'logo': None, 'elements': {}}
logo = root / 'assets' / 'logo.png'
if logo.exists():
    data['logo'] = 'data:image/png;base64,' + base64.b64encode(logo.read_bytes()).decode()
for f in sorted((root / 'assets' / 'elements').glob('*.png')):
    data['elements'][f.stem] = 'data:image/png;base64,' + base64.b64encode(f.read_bytes()).decode()
(root / 'assets-data.js').write_text('/* Generated by tools/build_assets.py. Do not edit by hand. */\nconst ASSET_DATA = ' + json.dumps(data) + ';\n')
print(f"assets-data.js: logo={'yes' if data['logo'] else 'no'}, {len(data['elements'])} pictures")
